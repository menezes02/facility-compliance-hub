app.patch("/api/notification-policies/:id/enabled", requireAuth, async (req, res) => {
  if (req.user!.role !== "admin" && req.user!.role !== "manager") {
    return res.status(403).json({ error: "Only admins or managers can update notification policies" });
  }

  const input = enabledSchema.parse(req.body);
  const result = await query<ApiNotificationPolicyRow>(
    `UPDATE notification_policies
     SET enabled = $1
     WHERE id = $2 AND org_id = $3
     RETURNING id, name, notification_type, channel, target_role, delay_minutes, repeat_count, enabled`,
    [input.enabled, req.params.id, req.user!.orgId]
  );

  if (!result.rows[0]) {
    return res.status(404).json({ error: "Notification policy not found" });
  }

  await writeAuditLog({
    orgId: req.user!.orgId,
    userId: req.user!.id,
    action: "NOTIFICATION_POLICY_TOGGLED",
    resourceType: "notification_policy",
    resourceId: result.rows[0].id,
    details: { name: result.rows[0].name, enabled: result.rows[0].enabled }
  });

  res.json(result.rows[0]);
});

app.get("/api/notification-deliveries", requireAuth, async (req, res) => {
  const result = await query<ApiNotificationDeliveryRow>(
    `SELECT notification_deliveries.id, notification_deliveries.notification_id, notification_deliveries.policy_id,
            notification_deliveries.channel, notification_deliveries.status, notification_deliveries.scheduled_for,
            notification_deliveries.delivered_at, notification_deliveries.attempt_number,
            notifications.title, notifications.type, notifications.related_task_id
     FROM notification_deliveries
     JOIN notifications ON notifications.id = notification_deliveries.notification_id
     WHERE notification_deliveries.org_id = $1
     ORDER BY notification_deliveries.created_at DESC
     LIMIT 100`,
    [req.user!.orgId]
  );
  res.json(result.rows);
});

app.post("/api/notifications/:id/read", requireAuth, async (req, res) => {
  const result = await query<ApiNotificationRow>(
    `UPDATE notifications
     SET is_read = TRUE
     WHERE id = $1 AND org_id = $2 AND (user_id IS NULL OR user_id = $3)
     RETURNING id, title, message, type, related_task_id, is_read,
               acknowledged_by, acknowledged_at, resolved_by, resolved_at, created_at`,
    [req.params.id, req.user!.orgId, req.user!.id]
  );
  if (result.rows[0]) {
    await writeAuditLog({
      orgId: req.user!.orgId,
      userId: req.user!.id,
      action: "NOTIFICATION_READ",
      resourceType: "notification",
      resourceId: result.rows[0].id,
      details: { title: result.rows[0].title, type: result.rows[0].type }
    });
  }
  res.json({ ok: true });
});

