async function processPendingDeliveries() {
  const deliveries = await query<ApiNotificationDeliveryRow>(
    `SELECT notification_deliveries.id, notification_deliveries.org_id,
            notification_deliveries.notification_id, notification_deliveries.policy_id,
            notification_deliveries.channel, notification_deliveries.status,
            notification_deliveries.scheduled_for, notification_deliveries.delivered_at,
            notification_deliveries.attempt_number,
            notifications.title, notifications.message, notifications.type,
            notifications.related_task_id, notifications.user_id,
            notification_policies.target_role
     FROM notification_deliveries
     JOIN notifications ON notifications.id = notification_deliveries.notification_id
     LEFT JOIN notification_policies ON notification_policies.id = notification_deliveries.policy_id
     WHERE notification_deliveries.status = 'pending'
       AND notification_deliveries.scheduled_for <= NOW()
     ORDER BY notification_deliveries.scheduled_for ASC
     LIMIT 100`
  );

  for (const delivery of deliveries.rows) {
    if (delivery.channel === "email") {
      await sendEmailDelivery(delivery);
    }

    await query(
      `UPDATE notification_deliveries
       SET status = 'sent',
           delivered_at = NOW()
       WHERE id = $1 AND status = 'pending'`,
      [delivery.id]
    );
  }

  return deliveries.rowCount ?? 0;
}

async function getNotificationRecipients(delivery: ApiNotificationDeliveryRow) {
  if (!delivery.org_id) return [];

  if (delivery.user_id) {
    const result = await query<{ email: string; first_name: string; last_name: string }>(
      `SELECT email, first_name, last_name
       FROM users
       WHERE org_id = $1 AND id = $2
       LIMIT 1`,
      [delivery.org_id, delivery.user_id]
    );
    return result.rows;
  }

  if (delivery.target_role) {
    const result = await query<{ email: string; first_name: string; last_name: string }>(
      `SELECT email, first_name, last_name
       FROM users
       WHERE org_id = $1 AND role = $2
       ORDER BY created_at ASC`,
      [delivery.org_id, delivery.target_role]
    );
    return result.rows;
  }

  const result = await query<{ email: string; first_name: string; last_name: string }>(
    `SELECT email, first_name, last_name
     FROM users
     WHERE org_id = $1 AND role IN ('admin', 'manager')
     ORDER BY CASE role WHEN 'admin' THEN 0 ELSE 1 END, created_at ASC`,
    [delivery.org_id]
  );
  return result.rows;
}

async function sendEmailDelivery(delivery: ApiNotificationDeliveryRow) {
  const recipients = await getNotificationRecipients(delivery);

  if (!recipients.length) {
    console.warn(`Email delivery ${delivery.id} has no recipients`);
    return;
  }

  if (!smtpTransport || !config.smtp.from) {
    console.log(
      `Email delivery ${delivery.id} mocked for ${recipients.map((recipient) => recipient.email).join(", ")}`
    );
    return;
  }

  await smtpTransport.sendMail({
    from: config.smtp.from,
    to: recipients.map((recipient) => recipient.email),
    subject: `[OperationHub] ${delivery.title}`,
    text: `${delivery.message ?? ""}\n\nOpen workspace: ${config.appUrl}`,
    html: `
      <div style="font-family: Arial, sans-serif; line-height: 1.5;">
        <h2>${delivery.title}</h2>
        <p>${delivery.message ?? ""}</p>
        <p><a href="${config.appUrl}">Open OperationHub workspace</a></p>
      </div>
    `
  });
}

async function fetchComplianceReportBundle(params: {
  orgId: string;
  vertical: string | null;
  days: number;
  generatedBy: string;
  customerId?: string | null;
}) {
  const [org, taskCounts, recentTasks, submissions, notifications, auditLogs] = await Promise.all([
    query<{ name: string; domain: string | null }>(
      `SELECT name, domain FROM organizations WHERE id = $1 LIMIT 1`,
      [params.orgId]
    ),
    query<{ status: string; count: string }>(
      `SELECT status, COUNT(*)::text AS count
       FROM tasks
       WHERE org_id = $1
         AND ($2::text IS NULL OR vertical = $2)
         AND created_at >= NOW() - ($3::int * INTERVAL '1 day')
         AND ($4::uuid IS NULL OR site_id IN (SELECT id FROM sites WHERE customer_id = $4))
       GROUP BY status
       ORDER BY status`,
      [params.orgId, params.vertical, params.days, params.customerId ?? null]
    ),
    query<ReportTaskRow>(
      `SELECT tasks.id, tasks.title, tasks.status, tasks.vertical, tasks.due_date,
              sites.name AS site_name, assets.name AS asset_name,
              CONCAT(users.first_name, ' ', users.last_name) AS assignee_name
       FROM tasks
       LEFT JOIN sites ON sites.id = tasks.site_id
       LEFT JOIN assets ON assets.id = tasks.asset_id
       LEFT JOIN users ON users.id = tasks.assigned_to
       WHERE tasks.org_id = $1
         AND ($2::text IS NULL OR tasks.vertical = $2)
         AND tasks.created_at >= NOW() - ($3::int * INTERVAL '1 day')
         AND ($4::uuid IS NULL OR sites.customer_id = $4)
       ORDER BY tasks.created_at DESC
       LIMIT 20`,
      [params.orgId, params.vertical, params.days, params.customerId ?? null]
    ),
    query<ReportSubmissionRow>(
      `SELECT submissions.id, tasks.title AS task_title, tasks.vertical,
              sites.name AS site_name, assets.name AS asset_name,
              CONCAT(users.first_name, ' ', users.last_name) AS submitted_by_name,
              jsonb_array_length(submissions.photo_urls)::text AS photo_count,
              submissions.created_at
       FROM submissions
       JOIN tasks ON tasks.id = submissions.task_id
       LEFT JOIN sites ON sites.id = tasks.site_id
       LEFT JOIN assets ON assets.id = tasks.asset_id
       LEFT JOIN users ON users.id = submissions.submitted_by
       WHERE submissions.org_id = $1
         AND ($2::text IS NULL OR tasks.vertical = $2)
         AND submissions.created_at >= NOW() - ($3::int * INTERVAL '1 day')
         AND ($4::uuid IS NULL OR sites.customer_id = $4)
       ORDER BY submissions.created_at DESC
       LIMIT 20`,
      [params.orgId, params.vertical, params.days, params.customerId ?? null]
    ),
    query<ReportNotificationRow>(
      `SELECT id, title, type, is_read, acknowledged_at, resolved_at, created_at
       FROM notifications
       WHERE org_id = $1
         AND created_at >= NOW() - ($2::int * INTERVAL '1 day')
       ORDER BY created_at DESC
       LIMIT 15`,
      [params.orgId, params.days]
    ),
    query<ReportAuditRow>(
      `SELECT audit_logs.id, audit_logs.action, audit_logs.resource_type,
              CONCAT(users.first_name, ' ', users.last_name) AS user_name,
              audit_logs.created_at
       FROM audit_logs
       LEFT JOIN users ON users.id = audit_logs.user_id
       WHERE audit_logs.org_id = $1
         AND audit_logs.created_at >= NOW() - ($2::int * INTERVAL '1 day')
       ORDER BY audit_logs.created_at DESC
       LIMIT 20`,
      [params.orgId, params.days]
    )
  ]);

  return {
    orgName: org.rows[0]?.name ?? "OperationHub",
    vertical: params.vertical,
    days: params.days,
    generatedBy: params.generatedBy,
    generatedAt: new Date().toISOString(),
    taskCounts: taskCounts.rows,
    recentTasks: recentTasks.rows,
    submissions: submissions.rows,
    notifications: notifications.rows,
    auditLogs: auditLogs.rows
  } satisfies ReportBundle;
}

async function createCorrectiveTaskFromTelemetry(params: {
  orgId: string;
  siteId: string;
  assetId?: string | null;
  vertical: "fire" | "parking" | "pool";
  title: string;
  description: string;
  teamId?: string | null;
}) {
  const existing = await query<{ id: string }>(
    `SELECT id
     FROM tasks
     WHERE org_id = $1
       AND site_id = $2
       AND COALESCE(asset_id::text, '') = COALESCE($3::text, '')
       AND vertical = $4
       AND title = $5
       AND status IN ('pending', 'in_progress', 'awaiting_review', 'overdue')
     LIMIT 1`,
    [params.orgId, params.siteId, params.assetId ?? null, params.vertical, params.title]
  );

  if (existing.rows[0]) return existing.rows[0].id;

  const assignee = await query<{ id: string }>(
    `SELECT id
     FROM users
     WHERE org_id = $1
     ORDER BY CASE role WHEN 'manager' THEN 0 WHEN 'admin' THEN 1 ELSE 2 END, created_at ASC
     LIMIT 1`,
    [params.orgId]
  );

  const created = await query<{ id: string }>(
    `INSERT INTO tasks (
       org_id, site_id, asset_id, title, description, vertical, assigned_to, team_id, due_date, schedule_type
     )
     VALUES ($1, $2, $3, $4, $5, $6, $7, $8, NOW() + INTERVAL '2 hours', 'one_time')
     RETURNING id`,
    [
      params.orgId,
      params.siteId,
      params.assetId ?? null,
      params.title,
      params.description,
      params.vertical,
      assignee.rows[0]?.id ?? null,
      params.teamId ?? null
    ]
  );

  return created.rows[0]?.id ?? null;
}

function matchesRuleComparator(rule: Pick<ApiAutomationRuleRow, "comparator" | "threshold_min" | "threshold_max">, readingValue?: number | null, readingText?: string | null) {
  if (rule.comparator === "any") return true;
  if (rule.comparator === "equals") {
    if (typeof readingValue === "number" && typeof rule.threshold_min === "number") {
      return readingValue === rule.threshold_min;
    }
    if (readingText && rule.threshold_min !== null) {
      return readingText === String(rule.threshold_min);
    }
    return false;
  }
  if (typeof readingValue !== "number") return false;
  if (rule.comparator === "lt" && typeof rule.threshold_min === "number") {
    return readingValue < rule.threshold_min;
  }
  if (rule.comparator === "gt" && typeof rule.threshold_min === "number") {
    return readingValue > rule.threshold_min;
  }
  if (rule.comparator === "outside_range" && typeof rule.threshold_min === "number" && typeof rule.threshold_max === "number") {
    return readingValue < rule.threshold_min || readingValue > rule.threshold_max;
  }
  return false;
}

async function fetchAutomationRules(orgId: string, triggerSource: "telemetry" | "task_overdue") {
  const result = await query<ApiAutomationRuleRow>(
    `SELECT automation_rules.id, automation_rules.name, automation_rules.vertical, automation_rules.trigger_source,
            automation_rules.event_type, automation_rules.comparator, automation_rules.threshold_min,
            automation_rules.threshold_max, automation_rules.severity_filter, automation_rules.task_status,
            automation_rules.action_type, automation_rules.action_title, automation_rules.action_message,
            automation_rules.target_team_id, teams.name AS target_team_name, automation_rules.enabled
     FROM automation_rules
     LEFT JOIN teams ON teams.id = automation_rules.target_team_id
     WHERE automation_rules.org_id = $1
       AND automation_rules.trigger_source = $2
       AND automation_rules.enabled = TRUE
     ORDER BY automation_rules.created_at ASC`,
    [orgId, triggerSource]
  );
  return result.rows;
}

async function applyTelemetryRules(params: {
  orgId: string;
  device: ApiDeviceRow;
  eventType: string;
  readingValue?: number | null;
  readingText?: string | null;
  severity: "info" | "warning" | "critical";
}) {
  const rules = await fetchAutomationRules(params.orgId, "telemetry");
  let generatedTaskId: string | null = null;

  for (const rule of rules) {
    if (rule.vertical && rule.vertical !== params.device.vertical) continue;
    if (rule.event_type && rule.event_type !== params.eventType) continue;
    if (rule.severity_filter && rule.severity_filter !== params.severity) continue;
    if (!matchesRuleComparator(rule, params.readingValue, params.readingText)) continue;

    if (rule.action_type === "create_task") {
      generatedTaskId =
        generatedTaskId ??
        (await createCorrectiveTaskFromTelemetry({
          orgId: params.orgId,
          siteId: params.device.site_id,
          assetId: params.device.asset_id,
          vertical: params.device.vertical,
          title: rule.action_title,
          description: rule.action_message,
          teamId: rule.target_team_id
        }));
    }

    if (rule.action_type === "notify" || rule.action_type === "create_task") {
      await createNotification({
        orgId: params.orgId,
        title: rule.action_title,
        message: generatedTaskId ? `${rule.action_message} Task generated automatically.` : rule.action_message,
        type: "rule",
        relatedTaskId: generatedTaskId
      });

      await writeAuditLog({
        orgId: params.orgId,
        action: "RULE_FIRED",
        resourceType: "automation_rule",
        resourceId: rule.id,
        details: {
          ruleName: rule.name,
          eventType: params.eventType,
          readingValue: params.readingValue,
          severity: params.severity,
          generatedTaskId
        }
      });
    }
  }

  return generatedTaskId;
}

async function runOverdueEscalations() {
  const tasksResult = await query<{
    id: string;
    org_id: string;
    vertical: "fire" | "parking" | "pool";
    status: "pending" | "in_progress" | "awaiting_review" | "overdue";
    due_date: string | null;
  }>(
    `SELECT id, org_id, vertical, status, due_date
     FROM tasks
     WHERE due_date IS NOT NULL
       AND due_date < NOW()
       AND status IN ('pending', 'in_progress', 'awaiting_review')`
  );

  let affected = 0;
  const rulesByOrg = new Map<string, ApiAutomationRuleRow[]>();

  for (const task of tasksResult.rows) {
    if (!rulesByOrg.has(task.org_id)) {
      rulesByOrg.set(task.org_id, await fetchAutomationRules(task.org_id, "task_overdue"));
    }
    const orgRules = rulesByOrg.get(task.org_id) ?? [];

    for (const rule of orgRules) {
      if (rule.vertical && rule.vertical !== task.vertical) continue;
      if (rule.task_status && rule.task_status !== task.status) continue;

      if (rule.action_type === "mark_overdue" && task.status !== "overdue") {
        await query(
          `UPDATE tasks
           SET status = 'overdue'
           WHERE id = $1 AND org_id = $2 AND status <> 'overdue'`,
          [task.id, task.org_id]
        );
        affected += 1;
      }

      await createNotification({
        orgId: task.org_id,
        title: rule.action_title,
        message: rule.action_message,
        type: "escalation",
        relatedTaskId: task.id
      });
    }
  }

  return affected;
}

