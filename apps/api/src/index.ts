function nextOccurrence(after: Date, rule: string) {
  const parts = rule.trim().split(/\s+/);
  if (parts.length !== 5) return null;

  const [minute, hour, dayOfMonth, month, dayOfWeek] = parts;
  const cursor = new Date(after);
  cursor.setSeconds(0, 0);
  cursor.setMinutes(cursor.getMinutes() + 1);

  for (let index = 0; index < 60 * 24 * 366; index += 1) {
    if (
      matchesCronPart(cursor.getMinutes(), minute) &&
      matchesCronPart(cursor.getHours(), hour) &&
      matchesCronPart(cursor.getDate(), dayOfMonth) &&
      matchesCronPart(cursor.getMonth(), month, 1) &&
      matchesCronPart(cursor.getDay(), dayOfWeek)
    ) {
      return cursor;
    }

    cursor.setMinutes(cursor.getMinutes() + 1);
  }

  return null;
}

async function generateNextRecurringTask(task: RecurringTaskRow) {
  if (!task.recurrence_rule) return false;

  const existingChild = await query<{ id: string }>(
    `SELECT id
     FROM tasks
     WHERE parent_task_id = $1
     LIMIT 1`,
    [task.id]
  );

  if (existingChild.rows[0]) return false;

  const nextDueDate = nextOccurrence(
    task.due_date ? new Date(task.due_date) : new Date(),
    task.recurrence_rule
  );

  if (!nextDueDate) return false;

  await query(
    `INSERT INTO tasks (
       org_id, site_id, asset_id, parent_task_id, template_id, title, description,
       vertical, status, assigned_to, due_date, schedule_type, recurrence_rule
     )
     VALUES ($1, $2, $3, $4, $5, $6, $7, $8, 'pending', $9, $10, 'recurring', $11)`,
    [
      task.org_id,
      task.site_id,
      task.asset_id,
      task.id,
      task.template_id,
      task.title,
      task.description,
      task.vertical,
      task.assigned_to,
      nextDueDate.toISOString(),
      task.recurrence_rule
    ]
  );

  recurringTasksGenerated.inc();
  return true;
}

async function syncRecurringTasks() {
  const recurringTasks = await query<RecurringTaskRow>(
    `SELECT id, org_id, site_id, asset_id, template_id, title, description, vertical,
            assigned_to, due_date, recurrence_rule
     FROM tasks
     WHERE schedule_type = 'recurring'
       AND recurrence_rule IS NOT NULL
       AND status IN ('closed', 'completed')`
  );

  let generatedCount = 0;

  for (const task of recurringTasks.rows) {
    if (await generateNextRecurringTask(task)) {
      generatedCount += 1;
    }
  }

  return generatedCount;
}

async function backfillRecurringTaskMetadata() {
  await query(
    `UPDATE tasks
     SET schedule_type = 'recurring',
         recurrence_rule = checklist_templates.recurrence
     FROM checklist_templates
     WHERE tasks.template_id = checklist_templates.id
       AND checklist_templates.recurrence IS NOT NULL
       AND (tasks.schedule_type IS DISTINCT FROM 'recurring' OR tasks.recurrence_rule IS NULL)`
  );
}

async function refreshBusinessMetrics() {
  const [tasksByStatus, submissionsByVertical, assetsByStatus, sitesByVertical, devicesByStatus] = await Promise.all([
    query<{ status: string; vertical: string; count: string }>(
      `SELECT status, vertical, COUNT(*)::text AS count
       FROM tasks
       GROUP BY status, vertical`
    ),
    query<{ vertical: string; count: string }>(
      `SELECT vertical, COUNT(*)::text AS count
       FROM submissions
       JOIN tasks ON tasks.id = submissions.task_id
       GROUP BY vertical`
    ),
    query<{ status: string; vertical: string; count: string }>(
      `SELECT status, vertical, COUNT(*)::text AS count
       FROM assets
       GROUP BY status, vertical`
    ),
    query<{ vertical: string; count: string }>(
      `SELECT vertical, COUNT(*)::text AS count
       FROM sites
       GROUP BY vertical`
    ),
    query<{ status: string; vertical: string; count: string }>(
      `SELECT status, vertical, COUNT(*)::text AS count
       FROM devices
       GROUP BY status, vertical`
    )
  ]);

  tasksByStatusGauge.reset();
  submissionsByVerticalGauge.reset();
  assetsByStatusGauge.reset();
  sitesByVerticalGauge.reset();
  devicesByStatusGauge.reset();

  for (const row of tasksByStatus.rows) {
    tasksByStatusGauge.set({ status: row.status, vertical: row.vertical }, Number(row.count));
  }

  for (const row of submissionsByVertical.rows) {
    submissionsByVerticalGauge.set({ vertical: row.vertical }, Number(row.count));
  }

  for (const row of assetsByStatus.rows) {
    assetsByStatusGauge.set({ status: row.status, vertical: row.vertical }, Number(row.count));
  }

  for (const row of sitesByVertical.rows) {
    sitesByVerticalGauge.set({ vertical: row.vertical }, Number(row.count));
  }

  for (const row of devicesByStatus.rows) {
    devicesByStatusGauge.set({ status: row.status, vertical: row.vertical }, Number(row.count));
  }
}

async function createNotification(params: {
  orgId: string;
  userId?: string | null;
  title: string;
  message: string;
  type: string;
  relatedTaskId?: string | null;
}) {
  const created = await query<{ id: string }>(
    `INSERT INTO notifications (org_id, user_id, title, message, type, related_task_id)
     VALUES ($1, $2, $3, $4, $5, $6)
     RETURNING id`,
    [
      params.orgId,
      params.userId ?? null,
      params.title,
      params.message,
      params.type,
      params.relatedTaskId ?? null
    ]
  );

  const notificationId = created.rows[0]?.id;
  if (!notificationId) return null;

  const policies = await query<ApiNotificationPolicyRow>(
    `SELECT id, name, notification_type, channel, target_role, delay_minutes, repeat_count, enabled
     FROM notification_policies
     WHERE org_id = $1
       AND enabled = TRUE
       AND (notification_type IS NULL OR notification_type = $2)
     ORDER BY created_at ASC`,
    [params.orgId, params.type]
  );

  for (const policy of policies.rows) {
    for (let attempt = 1; attempt <= policy.repeat_count; attempt += 1) {
      await query(
        `INSERT INTO notification_deliveries (
           org_id, notification_id, policy_id, channel, status, scheduled_for, attempt_number
         )
         VALUES ($1, $2, $3, $4, 'pending', NOW() + ($5 * INTERVAL '1 minute'), $6)`,
        [params.orgId, notificationId, policy.id, policy.channel, policy.delay_minutes * attempt, attempt]
      );
    }
  }

  return notificationId;
}

