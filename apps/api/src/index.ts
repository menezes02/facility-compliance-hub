function parseChecklistPayload(payload: string) {
  const parsed = JSON.parse(payload) as unknown;
  if (!Array.isArray(parsed)) {
    throw new Error("Checklist payload must be an array");
  }
  return parsed as ChecklistPayloadItem[];
}

function findMissingRequiredItems(items: ChecklistTemplateItem[], payload: ChecklistPayloadItem[], photoCount: number) {
  const byKey = new Map(payload.map((item) => [item.key, item]));

  return items
    .filter((item) => item.required)
    .filter((item) => {
      if (item.type === "photo") return photoCount === 0;
      const value = byKey.get(item.key)?.value;
      if (item.type === "checkbox") return typeof value !== "boolean";
      return value === null || value === undefined || String(value).trim() === "";
    })
    .map((item) => item.label);
}

function findFailedChecklistItems(taskVertical: string, payload: ChecklistPayloadItem[]) {
  const failures: string[] = [];

  for (const item of payload) {
    const value = item.value;
    const label = item.label ?? item.key;

    if (item.type === "checkbox" && value === false) {
      failures.push(label);
      continue;
    }

    if (typeof value === "string" && ["fault", "offline", "fail", "failed", "out_of_service"].includes(value.toLowerCase())) {
      failures.push(`${label}: ${value}`);
      continue;
    }

    const numericValue =
      typeof value === "number" ? value : typeof value === "string" && value.trim() ? Number(value) : Number.NaN;

    if (taskVertical === "pool" && item.key === "ph" && Number.isFinite(numericValue) && (numericValue < 7.2 || numericValue > 7.8)) {
      failures.push(`${label}: ${numericValue}`);
      continue;
    }

    if (taskVertical === "pool" && item.key === "chlorine" && Number.isFinite(numericValue) && (numericValue < 1 || numericValue > 3)) {
      failures.push(`${label}: ${numericValue}`);
    }
  }

  return failures;
}

