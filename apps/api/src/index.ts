function matchesCronPart(value: number, part: string, offset = 0) {
  if (part === "*") return true;
  return part
    .split(",")
    .map((entry) => Number(entry))
    .filter((entry) => Number.isInteger(entry))
    .includes(value + offset);
}

function writePdfSectionTitle(doc: PDFKit.PDFDocument, title: string) {
  doc.moveDown(1.1);
  doc.fontSize(15).fillColor("#0f172a").text(title);
  doc.moveTo(doc.x, doc.y + 3).lineTo(545, doc.y + 3).strokeColor("#cbd5e1").stroke();
  doc.moveDown(0.7);
}

function writePdfLine(doc: PDFKit.PDFDocument, label: string, value: string | number | null | undefined) {
  doc.fontSize(9).fillColor("#475569").text(label, { continued: true });
  doc.fillColor("#0f172a").text(` ${value ?? "n/a"}`);
}

function writePdfList(
  doc: PDFKit.PDFDocument,
  rows: string[],
  emptyText: string
) {
  if (!rows.length) {
    doc.fontSize(9).fillColor("#64748b").text(emptyText);
    return;
  }

  for (const row of rows) {
    if (doc.y > 735) doc.addPage();
    doc.fontSize(9).fillColor("#0f172a").text(`- ${row}`, { width: 500 });
  }
}

function createPdfBuffer(draw: (doc: PDFKit.PDFDocument) => void) {
  return new Promise<Buffer>((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: "A4" });
    const chunks: Buffer[] = [];

    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    draw(doc);
    doc.end();
  });
}

function csvEscape(value: unknown) {
  if (value === null || value === undefined) return "";
  const text = String(value);
  if (/[",\n\r]/.test(text)) {
    return `"${text.replace(/"/g, '""')}"`;
  }
  return text;
}

function rowsToCsv(headers: string[], rows: unknown[][]) {
  return [headers, ...rows].map((row) => row.map(csvEscape).join(",")).join("\n");
}

